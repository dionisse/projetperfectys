'use strict';
const assert = require('node:assert/strict');
const storage = new Map();
global.localStorage = { getItem: key => storage.get(key) || null, setItem: (key, val) => storage.set(key, String(val)), removeItem: key => storage.delete(key) };
const hr = require('../modern-proto/js/payroll-hr.js');
const folder = hr.createTestDossier().dossier;
const id = folder.id;
assert.deepEqual(hr.employeeDefinitionItems(id, 'socialSecurityFunds'), []);
assert.deepEqual(hr.employeeDefinitionItems(id, 'socialFunds'), []);
assert.equal(hr.seedDemoEmployeeDefinitionItems(id, 'socialSecurityFunds').ok, true);
const cnss = hr.employeeDefinitionItems(id, 'socialSecurityFunds')[0];
assert.equal(cnss.label, 'CNSS');
const a = hr.createEmployeeDefinitionItem(id, 'socialFunds', { label: 'Assureur A', address: '', testOnly: true }).item;
const b = hr.createEmployeeDefinitionItem(id, 'socialFunds', { label: 'Assureur B', address: '', testOnly: true }).item;
const base = { employeeNumber: 'INS-01', lastName: 'Fictif', firstName: 'Employé', testOnly: true };
const list = [{ insurerId: a.id, insuranceNumber: 'A-001' }, { insurerId: b.id, insuranceNumber: 'B-002' }];
const result = hr.createEmployee(id, { ...base, socialSecurityFundId: cnss.id, socialInsuranceNumber: 'SOC-003', supplementaryInsurances: list });
assert.equal(result.ok, true, result.errors.join('\n'));
const employeeId = result.employee.id;
let saved = hr.employee(id, employeeId);
assert.equal(saved.socialSecurityFundId, cnss.id);
assert.equal(saved.socialSecurityFundName, 'CNSS');
assert.equal(saved.socialInsuranceNumber, 'SOC-003');
assert.deepEqual(saved.supplementaryInsurances, list);
assert.equal(hr.deleteEmployeeDefinitionItem(id, 'socialSecurityFunds', cnss.id).ok, false);
assert.equal(hr.deleteEmployeeDefinitionItem(id, 'socialFunds', a.id).ok, false);
assert.equal(hr.updateEmployeeDefinitionItem(id, 'socialSecurityFunds', cnss.id, { label: 'Caisse sociale de test', address: '', testOnly: true }).ok, true);
assert.equal(hr.employee(id, employeeId).socialSecurityFundName, 'Caisse sociale de test');
assert.equal(hr.updateEmployeeDefinitionItem(id, 'socialFunds', a.id, { label: 'Assureur A modifié', address: '', testOnly: true }).ok, true);
assert.equal(hr.employeeDefinitionItems(id, 'socialFunds').find(item => item.id === a.id).label, 'Assureur A modifié');
assert.equal(hr.updateEmployee(id, employeeId, { supplementaryInsurances: [{ insurerId: 'absente', insuranceNumber: 'X' }] }).ok, false);
assert.equal(hr.updateEmployee(id, employeeId, { supplementaryInsurances: [{ insurerId: a.id, insuranceNumber: 'X'.repeat(81) }] }).ok, false);
assert.equal(hr.updateEmployee(id, employeeId, { supplementaryInsurances: 'invalide' }).ok, false);
assert.equal(hr.updateEmployee(id, employeeId, { socialSecurityFundId: a.id }).ok, false, 'un assureur complémentaire ne peut pas être choisi comme caisse sociale');
assert.deepEqual(hr.employee(id, employeeId).supplementaryInsurances, list, 'échec atomique sans modification');
assert.equal(hr.updateEmployee(id, employeeId, { supplementaryInsurances: [list[1]] }).ok, true);
assert.equal(hr.deleteEmployeeDefinitionItem(id, 'socialFunds', a.id).ok, true, 'la compagnie retirée peut être supprimée');
assert.equal(hr.updateEmployee(id, employeeId, { supplementaryInsurances: [], socialSecurityFundId: '' }).ok, true);
saved = hr.employee(id, employeeId);
assert.deepEqual(saved.supplementaryInsurances, []);
assert.equal(saved.socialSecurityFundName, '');
assert.equal(saved.socialInsuranceNumber, 'SOC-003', 'le numéro social reste indépendant du choix de caisse');
const legacy = hr.createEmployee(id, { ...base, employeeNumber: 'INS-LEGACY', supplementaryInsuranceCompany: 'Ancienne compagnie', supplementaryInsuranceNumber: 'OLD', testOnly: true });
assert.equal(legacy.ok, true);
assert.equal(hr.updateEmployee(id, legacy.employee.id, { supplementaryInsurances: [{ insurerId: b.id, insuranceNumber: 'NEW' }] }).ok, true);
saved = hr.employee(id, legacy.employee.id);
assert.equal(saved.supplementaryInsuranceCompany, 'Ancienne compagnie');
assert.equal(saved.supplementaryInsuranceNumber, 'OLD');
assert.equal(saved.socialSecurityFundId, undefined, 'pas de rattachement automatique d’une ancienne valeur');
assert.deepEqual(saved.supplementaryInsurances, [{ insurerId: b.id, insuranceNumber: 'NEW' }]);
const other = hr.createDossier({ clientName: 'Autre dossier', clientCode: 'AUT', cycleStart: '2026-01-01', cycleEnd: '2026-12-31' }).dossier;
assert.deepEqual(hr.employeeDefinitionItems(other.id, 'socialSecurityFunds'), []);
assert.equal(hr.createEmployee(other.id, { ...base, socialSecurityFundId: cnss.id }).ok, false);
assert.equal(hr.createEmployee(other.id, { ...base, supplementaryInsurances: [{ insurerId: b.id }] }).ok, false);
