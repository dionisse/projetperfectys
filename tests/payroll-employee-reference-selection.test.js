'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const storage = new Map();
global.localStorage = { getItem: k => storage.get(k) || null, setItem: (k, v) => storage.set(k, String(v)), removeItem: k => storage.delete(k) };
const hr = require('../modern-proto/js/payroll-hr.js');
const dossier = hr.createTestDossier().dossier;
const base = { employeeNumber: 'REF-01', lastName: 'Test', firstName: 'Employé', testOnly: true };
assert.equal(hr.createEmployee(dossier.id, { ...base, professionId: 'introuvable' }).ok, false, 'référence invalide refusée même si le catalogue est vide');
for (const kind of ['professions', 'socialFunds', 'banks']) assert.equal(hr.seedDemoEmployeeDefinitionItems(dossier.id, kind).ok, true);
const profession = hr.employeeDefinitionItems(dossier.id, 'professions')[0];
const fund = hr.employeeDefinitionItems(dossier.id, 'socialFunds')[0];
const [bank, destination] = hr.employeeDefinitionItems(dossier.id, 'banks');
const created = hr.createEmployee(dossier.id, { ...base, professionId: profession.id, socialFundId: fund.id, bankId: bank.id });
assert.equal(created.ok, true, created.errors.join('\n'));
let employee = hr.employee(dossier.id, created.employee.id);
assert.equal(employee.professionId, profession.id); assert.equal(employee.profession, profession.label);
assert.equal(employee.socialFundId, fund.id); assert.equal(employee.supplementaryInsuranceCompany, fund.label);
assert.equal(employee.bankId, bank.id); assert.equal(employee.bankName, bank.label);
assert.equal(hr.deleteEmployeeDefinitionItem(dossier.id, 'professions', profession.id).ok, false);
assert.equal(hr.deleteEmployeeDefinitionItem(dossier.id, 'socialFunds', fund.id).ok, false);
assert.equal(hr.deleteEmployeeDefinitionItem(dossier.id, 'banks', bank.id).ok, false);
assert.equal(hr.updateEmployee(dossier.id, employee.id, { bankId: 'absente' }).ok, false);
assert.equal(hr.updateEmployeeDefinitionItem(dossier.id, 'professions', profession.id, { code: profession.code, label: 'Profession modifiée', testOnly: true }).ok, true);
assert.equal(hr.employee(dossier.id, employee.id).profession, 'Profession modifiée');
assert.equal(hr.mergeEmployeeBanks(dossier.id, bank.id, destination.id).ok, true);
employee = hr.employee(dossier.id, employee.id);
assert.equal(employee.bankId, destination.id); assert.equal(employee.bankName, destination.label);
assert.equal(hr.updateEmployee(dossier.id, employee.id, { professionId: '', socialFundId: '', bankId: '' }).ok, true);
employee = hr.employee(dossier.id, employee.id);
assert.equal(employee.profession, ''); assert.equal(employee.supplementaryInsuranceCompany, ''); assert.equal(employee.bankName, '');
assert.equal(hr.updateEmployee(dossier.id, employee.id, { profession: 'Ancienne valeur' }).ok, true);
assert.equal(hr.updateEmployee(dossier.id, employee.id, { address: 'Adresse fictive' }).ok, true);
assert.equal(hr.employee(dossier.id, employee.id).profession, 'Ancienne valeur', 'ancienne valeur conservée sans correspondance arbitraire');
const app = fs.readFileSync(require('node:path').join(__dirname, '../modern-proto/js/app.js'), 'utf8');
for (const kind of ['professions', 'socialFunds', 'banks']) assert.ok(app.includes("PayrollHR.employeeDefinitionItems(dossier.id, '" + kind + "')"));
for (const field of ['professionId', 'socialSecurityFundId', 'bankId']) {
  assert.ok(app.includes("employeeReferenceField('" + field + "'"));
  assert.ok(app.includes("'" + field + "'"));
}
assert.match(app, /valeur enregistrée hors référentiel/);
assert.match(app, /Aucune définition dans le référentiel du dossier/);
// Les fonctions restent une sélection multiple du référentiel, sans création implicite.
assert.equal(hr.createEmployee(dossier.id, { ...base, employeeNumber: 'REF-INVALID', functionIds: ['absente'] }).ok, false);
assert.equal(hr.seedDemoEmployeeFunctions(dossier.id).ok, true);
const firstFunction = hr.employeeFunctions(dossier.id)[0];
const secondFunction = hr.createEmployeeFunction(dossier.id, { code: 'FIN', label: 'Finance', linkedPremiumIds: [], testOnly: true }).employeeFunction;
const multi = hr.createEmployee(dossier.id, { ...base, employeeNumber: 'REF-MULTI', functionIds: [firstFunction.id, secondFunction.id], paymentMethod: 'Virement Bancaire', bankId: destination.id });
assert.equal(multi.ok, true, multi.errors.join('\n'));
assert.deepEqual(multi.employee.functionIds, [firstFunction.id, secondFunction.id]);
assert.equal(hr.employee(dossier.id, multi.employee.id).paymentMethod, 'Virement Bancaire');
assert.equal(hr.employee(dossier.id, multi.employee.id).bankId, destination.id);
assert.equal(hr.updateEmployee(dossier.id, multi.employee.id, { functionIds: [secondFunction.id], paymentMethod: 'Mobile Money', bankId: '' }).ok, true);
assert.deepEqual(hr.employee(dossier.id, multi.employee.id).functionIds, [secondFunction.id]);
assert.equal(hr.employee(dossier.id, multi.employee.id).paymentMethod, 'Mobile Money');
assert.equal(hr.employee(dossier.id, multi.employee.id).bankName, '');
