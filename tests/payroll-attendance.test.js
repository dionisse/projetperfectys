'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const a=require('../modern-proto/js/payroll-attendance.js');
const weeks=a.calendarWeeks('2026-01');
assert.equal(weeks.length,5);
assert.deepEqual(weeks[0],['2025-12-29','2025-12-30','2025-12-31','2026-01-01','2026-01-02','2026-01-03','2026-01-04']);
assert.equal(weeks.at(-1).at(-1),'2026-02-01');
assert.ok(a.calendarWeeks('2024-02').flat().includes('2024-02-29'));
assert.throws(()=>a.calendarWeeks('2026-13'));
assert.equal(a.dayMinutes({start1:'08:00',end1:'12:00',start2:'13:00',end2:'17:30'}),510);
assert.equal(a.dayMinutes({start1:'22:00',end1:'02:15',next1:true}),255);
assert.equal(a.duration(255),'4 h 15');
assert.equal(a.dayMinutes({}),0);
for(const r of [{start1:'08:00'}, {end1:'12:00'}, {start1:'25:00',end1:'12:00'}, {start1:'22:00',end1:'02:00'}, {start1:'08:00',end1:'12:00',start2:'11:00',end2:'14:00'}, {next1:true}]) assert.throws(()=>a.dayMinutes(r));
assert.throws(()=>a.validateRecords({'2026-01-04':{start1:'22:00',end1:'02:00',next1:true},'2026-01-05':{start1:'01:00',end1:'03:00'}},'2026-12-31'));
assert.doesNotThrow(()=>a.validateRecords({'2026-01-04':{start1:'22:00',end1:'02:00',next1:true},'2026-01-05':{start1:'02:00',end1:'03:00'}},'2026-12-31'));
assert.throws(()=>a.validateRecords({'2026-12-31':{start1:'22:00',end1:'02:00',next1:true}},'2026-12-31'));
assert.throws(()=>a.validateRecords({'2026-02-30':{start1:'08:00',end1:'12:00'}},'2026-12-31','2026-01-01'));
assert.throws(()=>a.validateRecords({'2025-12-30':{start1:'08:00',end1:'12:00'}},'2026-12-31','2026-01-01'));
