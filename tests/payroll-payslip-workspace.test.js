'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const slips = require('../modern-proto/js/payroll-payslip-workspace.js');
assert.equal(slips.calculate('1000*2 + 500'), 2500);
assert.equal(slips.calculate('Puissance(2,3)'), 8);
assert.equal(slips.calculate('Racine(81,2)'), 9);
assert.equal(slips.calculate('Racine(-27,3)'), -3);
assert.equal(slips.calculate('Modulo(17,5)'), 2);
assert.equal(slips.calculate('-(1+2)*4'), -12);
for (const bad of ['1/0', 'Racine(-9,2)', 'Modulo(1,0)', 'alert(1)', '1;alert(1)', 'Puissance(2)', '']) assert.throws(() => slips.calculate(bad));
assert.equal(slips.numbers('125,50'), '125.50');
assert.equal(slips.numbers(''), '');
for (const bad of ['1e3','Infinity','12x','1234567890123']) assert.throws(() => slips.numbers(bad));
assert.deepEqual(slips.monthList({cycleStart:'2026-01-01',cycleEnd:'2026-03-31'}), ['2026-01','2026-02','2026-03']);
