'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const slips = require('../modern-proto/js/payroll-payslip-workspace.js');
const employee = {id:'e1', employeeNumber:'00123', firstName:'Jean Paul', lastName:'Désiré', displayName:'Désiré Jean Paul'};
assert.equal(slips.matchesEmployee(employee, '0123'), true);
assert.equal(slips.matchesEmployee(employee, 'desire jean'), true);
assert.equal(slips.matchesEmployee(employee, 'PAUL DÉSIRÉ'), true);
assert.equal(slips.matchesEmployee(employee, '  JEAN   PAUL '), true);
assert.equal(slips.matchesEmployee(employee, 'autre'), false);
assert.equal(slips.matchesEmployee(employee, ''), true);
assert.equal(slips.matchesEmployee({id:'EMP-01',firstName:'Ada',lastName:'Koffi'}, 'ada koffi'), true);
const hr = require('../modern-proto/js/payroll-hr.js');
const catalog = hr.employeeRubricCatalog();
const defaults = hr.employeeStatusDefaults().rubricIds;
assert.equal(defaults.length, 66);
const initial = slips.resolveRubrics(null, [], catalog);
assert.equal(initial.isDefaultPreview, true);
assert.deepEqual(initial.rows.map(row => row.id), defaults, 'aperçu de toutes les cases cochées par défaut');
const missing = slips.resolveRubrics({employeeStatus:''}, [], catalog);
assert.deepEqual(missing.rows.map(row => row.id), defaults);
const unknown = slips.resolveRubrics({employeeStatus:'Ancien statut'}, [], catalog);
assert.equal(unknown.isDefaultPreview, true);
assert.deepEqual(unknown.rows.map(row => row.id), defaults);
const customIds = [catalog[0].id, catalog.find(row => !row.selectedByReference).id];
const customStatus = {id:'s1', rubricIds:customIds};
const custom = slips.resolveRubrics({employeeStatus:'s1'}, [customStatus], catalog);
assert.equal(custom.isDefaultPreview, false);
assert.deepEqual(custom.rows.map(row => row.id), catalog.filter(row => customIds.includes(row.id)).map(row => row.id));
const empty = slips.resolveRubrics({employeeStatus:'s1'}, [{id:'s1',rubricIds:[]}], catalog);
assert.equal(empty.isDefaultPreview, false);
assert.deepEqual(empty.rows, [], 'une sélection volontairement vide ne doit pas être remplacée');
assert.equal(slips.calculate('1000*2 + 500'), 2500);
assert.equal(slips.calculate('Puissance(2,3)'), 8);
assert.equal(slips.calculate('Racine(81,2)'), 9);
assert.equal(slips.calculate('Racine(-27,3)'), -3);
assert.equal(slips.calculate('Modulo(17,5)'), 2);
assert.equal(slips.calculate('-(1+2)*4'), -12);
for (const bad of ['1/0', 'Racine(-9,2)', 'Modulo(1,0)', 'alert(1)', '1;alert(1)', 'Puissance(2)', '']) assert.throws(() => slips.calculate(bad));
assert.equal(slips.numbers('125,50'), '125.50');
assert.equal(slips.numbers(''), '');
for (const bad of ['1e3','Infinity','12x','1234567890123']) assert.throws(() => slips.numbers(bad));
assert.deepEqual(slips.monthList({cycleStart:'2026-01-01',cycleEnd:'2026-03-31'}), ['2026-01','2026-02','2026-03']);
const root=path.join(__dirname,'..');
const src=fs.readFileSync(path.join(root,'modern-proto/js/payroll-payslip-workspace.js'),'utf8');
const app=fs.readFileSync(path.join(root,'modern-proto/js/app.js'),'utf8');
const html=fs.readFileSync(path.join(root,'modern-proto/index.html'),'utf8');
const worker=fs.readFileSync(path.join(root,'modern-proto/service-worker.js'),'utf8');
assert.ok(html.indexOf('js/payroll-payslip-workspace.js') < html.indexOf('js/app.js'));
assert.match(worker, /\.\/js\/payroll-payslip-workspace\.js/);
assert.match(app, /id === 'payslips'[\s\S]*payroll-payslip-workspace/);
assert.match(src, /employeeStatus/);
assert.match(src, /employeeRubricCatalog\(\)/);
assert.match(src, /isDemoTestDossier\(dossierId\)/);
assert.match(src, /record\.edit|options\.canEdit\(\)/);
assert.match(src, /root\.confirm\('Appliquer '/);
assert.match(src, /data-rule-load/);
assert.doesNotMatch(src, /\beval\s*\(|\bnew Function\s*\(/);
